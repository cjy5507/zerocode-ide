#!/usr/bin/env python3
"""Prepare a worktree's Node dependencies before the pre-handin checks."""

import os
import stat
import subprocess
import sys
from pathlib import Path


def prepare():
    link = Path("node_modules")
    try:
        mode = link.lstat().st_mode
    except FileNotFoundError:
        pass
    else:
        if stat.S_ISLNK(mode):
            if not link.exists():
                return "node_modules is a broken symlink; leaving it in place"
            return "node_modules already exists (symlink)"
        if stat.S_ISDIR(mode):
            return "node_modules already exists (directory)"
        return "node_modules already exists (other entry)"

    git = subprocess.run(
        ["git", "rev-parse", "--path-format=absolute", "--git-common-dir"],
        capture_output=True,
    )
    if git.returncode:
        return f"could not find the Git common directory: {os.fsdecode(git.stderr).strip()}"

    main = Path(os.fsdecode(git.stdout.rstrip(b"\r\n"))).parent.resolve()
    if Path.cwd().resolve() == main:
        return "node_modules is missing in the main checkout; no link to create"

    source = main / link.name
    if not source.is_dir():
        return f"no node_modules directory to link at {str(source)!r}"

    link.symlink_to(source, target_is_directory=True)
    return f"linked node_modules to {str(source)!r}"


if __name__ == "__main__":
    try:
        message = prepare()
    except OSError as error:
        message = f"could not link node_modules: {error}"
    print("pre-handin: " + " ".join(message.splitlines()), file=sys.stderr)
