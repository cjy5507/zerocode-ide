#!/usr/bin/env python3
"""Exercise pre-handin's dependency link with local Git worktrees."""

import os
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

SCRIPT = Path(__file__).resolve().parents[1] / "link_node_modules.py"


class LinkNodeModules(unittest.TestCase):
    def setUp(self):
        scratch = tempfile.TemporaryDirectory()
        self.addCleanup(scratch.cleanup)
        self.scratch = Path(scratch.name)
        self.main = self.scratch / "main checkout"
        self.worktree = self.scratch / "linked worktree"
        self.source = self.main / "node_modules"
        self.link = self.worktree / "node_modules"
        self.env = {
            **os.environ,
            "GIT_CONFIG_NOSYSTEM": "1",
            "GIT_CONFIG_GLOBAL": os.devnull,
            "GIT_CEILING_DIRECTORIES": str(self.scratch.resolve().parent),
        }

        self.main.mkdir()
        self.git("init", "-q")
        self.git(
            "-c", "user.name=Test", "-c", "user.email=test@example.com",
            "commit", "--allow-empty", "-qm", "fixture",
        )
        self.git("worktree", "add", "-q", "--detach", str(self.worktree))

    def git(self, *args):
        subprocess.run(["git", *args], cwd=self.main, env=self.env, check=True)

    def run_script(self, checkout, *python_args):
        result = subprocess.run(
            [sys.executable, *python_args, str(SCRIPT)],
            cwd=checkout, env=self.env, capture_output=True, text=True,
        )
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(result.stdout, "")
        lines = result.stderr.splitlines()
        self.assertEqual(len(lines), 1, result.stderr)
        self.assertTrue(lines[0].startswith("pre-handin: "), result.stderr)
        return lines[0]

    @unittest.skipIf(os.name == "nt", "symlink creation needs Windows developer mode")
    def test_links_the_main_directory_when_checkout_paths_have_spaces(self):
        self.source.mkdir()
        message = self.run_script(self.worktree)
        self.assertTrue(self.link.is_symlink(), message)
        self.assertEqual(self.link.resolve(), self.source.resolve())
        self.assertEqual(message, f"pre-handin: linked node_modules to {str(self.source.resolve())!r}")

    def test_keeps_an_existing_directory(self):
        self.source.mkdir()
        self.link.mkdir()
        marker = self.link / "local"
        marker.write_text("keep this")
        self.assertIn("already exists (directory)", self.run_script(self.worktree))
        self.assertFalse(self.link.is_symlink())
        self.assertEqual(marker.read_text(), "keep this")

    def test_keeps_an_existing_file(self):
        self.source.mkdir()
        self.link.write_text("keep this")
        self.assertIn("already exists (other entry)", self.run_script(self.worktree))
        self.assertFalse(self.link.is_symlink())
        self.assertEqual(self.link.read_text(), "keep this")

    @unittest.skipIf(os.name == "nt", "symlink creation needs Windows developer mode")
    def test_keeps_an_existing_symlink_to_a_different_directory(self):
        self.source.mkdir()
        local = self.worktree / "local dependencies"
        local.mkdir()
        self.link.symlink_to(local.name, target_is_directory=True)
        self.assertIn("already exists (symlink)", self.run_script(self.worktree))
        self.assertEqual(self.link.readlink(), Path(local.name))

    @unittest.skipIf(os.name == "nt", "symlink creation needs Windows developer mode")
    def test_keeps_a_broken_symlink(self):
        self.source.mkdir()
        missing = Path("missing dependencies")
        self.link.symlink_to(missing, target_is_directory=True)
        self.assertIn("broken symlink", self.run_script(self.worktree))
        self.assertEqual(self.link.readlink(), missing)
        self.assertFalse(self.link.exists())

    def test_skips_the_link_when_the_main_checkout_has_no_dependencies(self):
        self.assertIn("no node_modules directory to link", self.run_script(self.worktree))
        self.assertFalse(os.path.lexists(self.link))

    def test_skips_the_link_in_the_main_checkout(self):
        self.assertIn("missing in the main checkout", self.run_script(self.main))
        self.assertFalse(os.path.lexists(self.source))

    def test_skips_the_link_outside_git(self):
        self.assertIn("could not find the Git common directory", self.run_script(self.scratch))
        self.assertFalse(os.path.lexists(self.scratch / "node_modules"))

    def test_leaves_the_worktree_alone_when_symlink_creation_is_denied(self):
        self.source.mkdir()
        denied = """
import runpy
import sys
from pathlib import Path
from unittest.mock import patch

with patch.object(Path, 'symlink_to', side_effect=PermissionError('permission denied')):
    runpy.run_path(sys.argv[1], run_name='__main__')
"""
        self.assertIn("could not link node_modules: permission denied", self.run_script(self.worktree, "-c", denied))
        self.assertFalse(os.path.lexists(self.link))


if __name__ == "__main__":
    unittest.main()
